-- Référentiel BABOK v3 (ticket 06, ADR-0012) : 6 domaines de connaissance,
-- 30 tâches, 50 techniques et la correspondance entre tâches et techniques.
-- Identique pour toutes les initiatives, en lecture seule pour tous,
-- administrateur compris : seule une migration le modifie.
--
-- Chaque élément porte un identifiant stable (le numéro de section du BABOK v3,
-- référencé par les autres objets), son renvoi de section, son nom officiel en
-- anglais et en français, et un résumé rédigé pour ACTA dans les deux langues.
-- Aucun texte de l'IIBA n'est reproduit.

CREATE TABLE babok_knowledge_area (
  id         text PRIMARY KEY,
  -- Renvoi de section ; égal à l'identifiant en v3, il peut en différer dans une
  -- édition ultérieure du guide (ADR-0012, conséquences).
  section    text NOT NULL,
  position   smallint NOT NULL UNIQUE,  -- ordre du guide
  name_en    text NOT NULL,
  name_fr    text NOT NULL,
  summary_en text NOT NULL,
  summary_fr text NOT NULL
);

CREATE TABLE babok_task (
  id                text PRIMARY KEY,
  knowledge_area_id text NOT NULL REFERENCES babok_knowledge_area (id),
  section           text NOT NULL,
  position          smallint NOT NULL UNIQUE,
  name_en           text NOT NULL,
  name_fr           text NOT NULL,
  summary_en        text NOT NULL,
  summary_fr        text NOT NULL
);

CREATE TABLE babok_technique (
  id         text PRIMARY KEY,
  section    text NOT NULL,
  position   smallint NOT NULL UNIQUE,
  name_en    text NOT NULL,
  name_fr    text NOT NULL,
  summary_en text NOT NULL,
  summary_fr text NOT NULL
);

-- Techniques que le BABOK associe à chaque tâche.
CREATE TABLE babok_task_technique (
  task_id      text NOT NULL REFERENCES babok_task (id),
  technique_id text NOT NULL REFERENCES babok_technique (id),
  PRIMARY KEY (task_id, technique_id)
);
CREATE INDEX babok_task_technique_technique_id_idx ON babok_task_technique (technique_id);

-- Row Level Security : lecture par tout utilisateur connecté ; aucune politique
-- d'écriture, donc aucune écriture possible avec le compte applicatif.
ALTER TABLE babok_knowledge_area ENABLE ROW LEVEL SECURITY;
ALTER TABLE babok_task ENABLE ROW LEVEL SECURITY;
ALTER TABLE babok_technique ENABLE ROW LEVEL SECURITY;
ALTER TABLE babok_task_technique ENABLE ROW LEVEL SECURITY;

CREATE POLICY babok_knowledge_area_select ON babok_knowledge_area FOR SELECT
  USING (current_app_user_id() IS NOT NULL);
CREATE POLICY babok_task_select ON babok_task FOR SELECT
  USING (current_app_user_id() IS NOT NULL);
CREATE POLICY babok_technique_select ON babok_technique FOR SELECT
  USING (current_app_user_id() IS NOT NULL);
CREATE POLICY babok_task_technique_select ON babok_task_technique FOR SELECT
  USING (current_app_user_id() IS NOT NULL);

